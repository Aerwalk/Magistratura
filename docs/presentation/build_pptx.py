def _set_font(run, size, bold=False, color=INK, italic=False):
    f = run.font
    f.name = FONT
    f.size = Pt(size)
    f.bold = bold
    f.italic = italic
    f.color.rgb = color


def tx(slide, x, y, w, h, lines, size=16, bold=False, color=INK, align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP, line_spacing=1.12):
    """lines: list of (text, size, bold, color) or plain str."""
    box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = box.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    tf.margin_left = 0
    tf.margin_right = 0
    tf.margin_top = 0
    tf.margin_bottom = 0
    first = True
    for ln in lines:
        if isinstance(ln, str):
            ln = (ln, size, bold, color)
        para = tf.paragraphs[0] if first else tf.add_paragraph()
        first = False
        para.alignment = align
        para.line_spacing = line_spacing
        r = para.add_run()
        r.text = ln[0]
        _set_font(r, ln[1], ln[2], ln[3])
    return box


def rect(slide, x, y, w, h, fill=CARD, line=LINE, shape=MSO_SHAPE.ROUNDED_RECTANGLE):
    sp = slide.shapes.add_shape(shape, Inches(x), Inches(y), Inches(w), Inches(h))
    sp.fill.solid()
    sp.fill.fore_color.rgb = fill
    sp.line.color.rgb = line
    sp.line.width = Pt(1)
    if shape == MSO_SHAPE.ROUNDED_RECTANGLE:
        try:
            sp.adjustments[0] = 0.07
        except Exception:
            pass
    sp.shadow.inherit = False
    return sp


def bg_fill(slide, color):
    rect(slide, -0.2, -0.2, 13.9, 8.0, fill=color, line=color, shape=MSO_SHAPE.RECTANGLE)


def kicker(slide, text, color=GREEN, x=0.6, y=0.45):
    tx(slide, x, y, 12, 0.4, [(text.upper(), 13, True, color)])


def title_block(slide, kicker_text, title_text, lead_text=None):
    kicker(slide, kicker_text)
    tx(slide, 0.6, 0.9, 12.1, 0.9, [(title_text, 34, True, INK)])
    if lead_text:
        tx(slide, 0.6, 1.78, 12.1, 0.8, [(lead_text, 15.5, False, MUTED)])


def card(slide, x, y, w, h, badge, badge_color, head, body):
    rect(slide, x, y, w, h)
    if badge:
        bx = rect(slide, x + 0.28, y + 0.3, 0.55, 0.55, fill=badge_color, line=badge_color, shape=MSO_SHAPE.ROUNDED_RECTANGLE)
        tf = bx.text_frame
        tf.margin_left = 0
        tf.margin_right = 0
        tf.margin_top = 0
        tf.margin_bottom = 0
        p = tf.paragraphs[0]
        p.alignment = PP_ALIGN.CENTER
        r = p.add_run()
        r.text = badge
        _set_font(r, 16, True, WHITE)
    tx(slide, x + 0.28, y + 1.0, w - 0.56, 0.55, [(head, 16.5, True, INK)])
    tx(slide, x + 0.28, y + 1.72, w - 0.56, h - 1.9, [(body, 13.5, False, MUTED)], line_spacing=1.18)


def bullets(slide, x, y, w, items, size=14.5, gap=0.06, color=INK):
    for i, item in enumerate(items):
        p = tx(slide, x, y + i * (size / 26.0 + 0.32), w, 0.8, [(item, size, False, color)], line_spacing=1.12)
    return p


